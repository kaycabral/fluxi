// LOCAL-ONLY helpers for the `pluggy-sync` Edge Function
// (supabase/functions/pluggy-sync). Production never runs this: there the
// secrets are set once by the runbook (docs/production.md) and pg_cron calls
// the function.
//
//   pnpm pluggy:env [-- --email dev@fluxi.local]
//     Gives `fluxi_sync` LOGIN + a fresh random password in the LOCAL stack and
//     writes the gitignored `supabase/functions/.env` (mode 600): Pluggy
//     credentials from ~/.config/fluxi/pluggy.env (the DEMO app; env vars are
//     ignored on purpose so local never points at prod), the user's id, the
//     role's connection URL inside the Docker network, a random token and
//     the holder-key secret (kept across runs, so company keys stay stable).
//   pnpm pluggy:serve   (another terminal; serves the function locally)
//   pnpm pluggy:sync
//     POSTs to the local function with the token and prints its JSON summary
//     (aggregates only).
//
// Never prints secrets.

import { parsePluggyConfig } from '@/features/bank-feed/core/pluggy'
import { readLocalSupabase } from '@cbrl/supabase/local'
import { randomBytes } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import path from 'node:path'
import { parseArgs } from 'node:util'
import pg from 'pg'

const ENV_FILE = path.resolve('supabase', 'functions', '.env')
/** The local stack's Postgres as seen from the edge-runtime container (Docker alias; Deno rejects the underscore in the container name). */
const DOCKER_DB_HOST = 'db:5432'
const LOCAL_HOSTS = new Set(['localhost', '127.0.0.1'])

const { positionals, values } = parseArgs({
  args: process.argv.slice(2).filter((arg) => arg !== '--'),
  allowPositionals: true,
  options: { email: { type: 'string', default: 'dev@fluxi.local' } },
})

function localDbUrl(): string {
  const url = readLocalSupabase().dbUrl
  if (!LOCAL_HOSTS.has(new URL(url).hostname)) throw new Error('refusing a non-local database')
  return url
}

/** The holder-key secret already in the local env file, so company keys survive a re-run. */
async function existingHolderSecret(): Promise<string | null> {
  const current = await readFile(ENV_FILE, 'utf8').catch(() => '')
  const line = current.split('\n').find((l) => l.startsWith('FLUXI_HOLDER_KEY_SECRET='))
  const value = line?.slice('FLUXI_HOLDER_KEY_SECRET='.length).trim() ?? ''
  return value.length >= 32 ? value : null
}

async function writeEnv(): Promise<void> {
  const file = await readFile(path.join(homedir(), '.config', 'fluxi', 'pluggy.env'), 'utf8')
  const pluggy = parsePluggyConfig(file, {})
  const client = new pg.Client({ connectionString: localDbUrl() })
  await client.connect()
  try {
    const user = await client.query<{ id: string }>(
      'select id from auth.users where lower(email) = lower($1) limit 1',
      [values.email],
    )
    const userId = user.rows[0]?.id
    if (!userId) throw new Error('no local user with that email (run pnpm db:seed)')
    const password = randomBytes(32).toString('hex')
    // Hex only, so it is safe inside the literal (ALTER ROLE takes no parameters).
    await client.query(`alter role fluxi_sync login password '${password}'`)
    const lines = {
      PLUGGY_CLIENT_ID: pluggy.clientId,
      PLUGGY_CLIENT_SECRET: pluggy.clientSecret,
      PLUGGY_ITEM_IDS: pluggy.itemIds.join(','),
      FLUXI_SYNC_USER_ID: userId,
      FLUXI_SYNC_DB_URL: `postgresql://fluxi_sync:${password}@${DOCKER_DB_HOST}/postgres`,
      FLUXI_SYNC_TOKEN: randomBytes(32).toString('hex'),
      FLUXI_HOLDER_KEY_SECRET: (await existingHolderSecret()) ?? randomBytes(32).toString('hex'),
    }
    // The same Vault secrets the pg_cron job reads (migration 0015), pointing at
    // the local gateway inside the Docker network.
    for (const [name, value] of [
      ['pluggy_sync_url', 'http://kong:8000/functions/v1/pluggy-sync'],
      ['pluggy_sync_token', lines.FLUXI_SYNC_TOKEN],
    ] as const) {
      const updated = await client.query(
        'select vault.update_secret(id, $2) from vault.secrets where name = $1',
        [name, value],
      )
      if (updated.rowCount === 0) {
        await client.query('select vault.create_secret($2, $1)', [name, value])
      }
    }
    const body = Object.entries(lines)
      .map(([key, value]) => `${key}=${value}`)
      .join('\n')
    await writeFile(ENV_FILE, `# Generated by pnpm pluggy:env (local only).\n${body}\n`, {
      mode: 0o600,
    })
    console.log(`wrote ${path.relative(process.cwd(), ENV_FILE)} for ${values.email}`)
  } finally {
    await client.end()
  }
}

async function invoke(): Promise<void> {
  const env = new Map<string, string>()
  for (const line of (await readFile(ENV_FILE, 'utf8')).split('\n')) {
    const eq = line.indexOf('=')
    if (eq > 0 && !line.startsWith('#')) env.set(line.slice(0, eq), line.slice(eq + 1))
  }
  const token = env.get('FLUXI_SYNC_TOKEN')
  if (!token) throw new Error('run pnpm pluggy:env first')
  const response = await fetch(`${readLocalSupabase().apiUrl}/functions/v1/pluggy-sync`, {
    method: 'POST',
    headers: { 'x-fluxi-sync-token': token, 'Content-Type': 'application/json' },
    body: '{}',
  })
  console.log(`HTTP ${response.status}`)
  console.log(JSON.stringify(await response.json(), null, 2))
  if (!response.ok) process.exitCode = 1
}

const commands: Record<string, () => Promise<void>> = { env: writeEnv, sync: invoke }
const run = commands[positionals[0] ?? '']
if (run === undefined) {
  console.error('usage: tsx scripts/pluggy-local.ts <env|sync>')
  process.exitCode = 1
} else {
  run().catch((err: unknown) => {
    console.error(err instanceof Error ? err.message : 'failed')
    process.exitCode = 1
  })
}
